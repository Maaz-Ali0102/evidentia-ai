"""Regenerate the auto appendix of reports/ML_REPORT.md from the raw metric files and samples.

Everything after the marker line is replaced, so every number in the appendix is copied
by code from reports/metrics/*.json, models/registry.json and data/samples/ (no pandas needed).
Usage: .venv/Scripts/python scripts/build_report_appendix.py
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "reports" / "ML_REPORT.md"
MET = ROOT / "reports" / "metrics"
SAMPLES = ROOT / "data" / "samples"
MARKER = "<!-- APPENDIX:AUTO (everything below is generated by scripts/build_report_appendix.py) -->"
MODEL = {"logreg": "LR", "random_forest": "RF"}
csv.field_size_limit(10_000_000)


def load(name: str) -> dict:
    return json.loads((MET / f"{name}.json").read_text(encoding="utf-8"))


def table(head: list[str], rows: list[list]) -> str:
    def cell(v):
        if v is None:
            return "–"
        if isinstance(v, float):
            return f"{v:.4f}".rstrip("0").rstrip(".") if v != int(v) or abs(v) < 1 else f"{v:g}"
        if isinstance(v, int):
            return f"{v:,}"
        return str(v).replace("|", "\\|").replace("\n", " ")
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def cm_table(cm: list[list[int]], labels: list[str]) -> str:
    return table(["true \\ predicted"] + labels, [[labels[i]] + row for i, row in enumerate(cm)])


def appendix() -> str:
    s2, s1, tc, iso = load("stage2"), load("stage1"), load("three_class"), load("iforest")
    wp = load("stage1_within_product")
    reg = json.loads((ROOT / "models" / "registry.json").read_text(encoding="utf-8"))
    L = [MARKER, "", "## Appendix A. Raw metrics (generated from `reports/metrics/*.json`)", ""]

    L += ["### A.1 Stage 2 split sizes", "",
          table(["Split", "Train rows", "Train malicious", "Test rows", "Test malicious"],
                [[k, v["train"], v["train_malicious"], v["test"], v["test_malicious"]]
                 for k, v in s2["split_sizes"].items()]), ""]

    rows = []
    for split, fsd in s2["ablation_untuned"].items():
        for fs, md in fsd.items():
            for m, r in md.items():
                mal = r["per_class"]["malicious"]
                rows.append([split, fs, MODEL[m], r["positive_rate_baseline"], r["pr_auc_positive"], r["roc_auc"],
                             r["macro_f1"], mal["precision"], mal["recall"], r["train_seconds"]])
    L += ["### A.2 Stage 2 untuned feature ablation (test window, threshold 0.5)", "",
          table(["Split", "Features", "Model", "Chance", "PR-AUC", "ROC-AUC", "Macro-F1", "Mal. precision",
                 "Mal. recall", "Train s"], rows), ""]

    L += ["### A.3 Stage 2 tuned models: every grid-search candidate (CV PR-AUC on the training window)", ""]
    for split, md in s2["tuned"].items():
        for m, r in md.items():
            cands = [[c["feature_set"], ", ".join(f"{k.replace('clf__', '')}={v}" for k, v in c.items()
                                                  if k.startswith("clf__")), c["pr_auc"]] for c in r["cv_results"]]
            L += [f"**{split} · {MODEL[m]}** — selected `{r['selected_feature_set']}` "
                  f"{r['selected_params']}, threshold {r['threshold_from_train_oof']}, "
                  f"tuning {r['tuning_seconds']} s", "",
                  table(["Features", "Hyper-parameters", "CV PR-AUC"], cands), ""]

    rows = []
    for split, md in s2["tuned"].items():
        for m, r in md.items():
            t, h = r["test_at_tuned_threshold"], r["test_at_0.5"]
            mal = t["per_class"]["malicious"]
            rows.append([split, MODEL[m], r["cv_pr_auc_mean"], t["pr_auc_positive"], t["roc_auc"], t["accuracy"],
                         t["macro_f1"], mal["precision"], mal["recall"], mal["f1"], h["macro_f1"],
                         f"{r['incident_level']['detected']}/{r['incident_level']['incidents']}",
                         r["inference_ms_per_1k_rows"], r["model_size_mb"]])
    L += ["### A.4 Stage 2 tuned models on the test window", "",
          table(["Split", "Model", "CV PR-AUC", "Test PR-AUC", "ROC-AUC", "Accuracy", "Macro-F1",
                 "Mal. P", "Mal. R", "Mal. F1", "Macro-F1 @0.5", "Incidents hit", "ms / 1k rows", "MB"], rows), ""]
    for split, md in s2["tuned"].items():
        for m, r in md.items():
            L += [f"Confusion matrix, {split} · {MODEL[m]} (tuned threshold):", "",
                  cm_table(r["test_at_tuned_threshold"]["confusion_matrix"], ["suspicious", "malicious"]), ""]

    rows = []
    for fs, md in s1["results"].items():
        for m, r in md.items():
            a = r["per_class"]["alert"]
            rows.append([fs, MODEL[m], r["accuracy"], r["macro_f1"], r["pr_auc_positive"], r["roc_auc"],
                         a["precision"], a["recall"], r["confusion_matrix"][0][1], r["confusion_matrix"][1][0],
                         r["train_seconds"], r["inference_ms_per_1k_rows"]])
    L += ["### A.5 Stage 1 (benign vs alert), all products", "",
          f"Train rows {s1['train_rows']:,} ({s1['train_alerts']:,} alerts, {s1['train_benign_sampled']:,} sampled "
          f"benign); test rows {s1['test_rows']:,} ({s1['test_alerts']:,} alerts).", "",
          table(["Features", "Model", "Accuracy", "Macro-F1", "PR-AUC", "ROC-AUC", "Alert P", "Alert R",
                 "False alerts", "Missed alerts", "Train s", "ms / 1k rows"], rows), ""]

    lt = wp["label_is_function_of_event_type"]
    rows = []
    for p, e in wp["products"].items():
        if e["tested"]:
            w = e["within_product_model"]
            rows.append([p, e["train_rows"], e["train_alerts"], e["test_rows"], e["test_alerts"]]
                        + [w[fs][m]["pr_auc_positive"] for fs, m in
                           [("full", "logreg"), ("full", "random_forest"), ("text", "logreg"), ("context", "logreg")]])
    b = lt["lookup_table_baseline_on_test"]
    L += ["### A.6 Stage 1 inside a single product", "",
          table(["Product", "Train rows", "Train alerts", "Test rows", "Test alerts", "LR full", "RF full",
                 "LR text", "LR context"], rows), "",
          f"(product, message_type) pairs: {lt['distinct_product_message_type_keys']}; pairs containing both "
          f"classes: {lt['keys_with_both_benign_and_alert']}; lookup-table baseline on {b['n']:,} test rows: "
          f"macro-F1 {b['macro_f1']}, confusion matrix {b['confusion_matrix']}; test rows with an unseen pair: "
          f"{lt['test_rows_with_key_unseen_in_train']} ({lt['test_alerts_with_key_unseen_in_train']} alerts).", "",
          "Products not tested:", ""]
    L += [f"- {p or '(blank)'}: {e['reason']}" for p, e in wp["products"].items() if not e["tested"]] + [""]

    L += ["### A.7 Three classes (all test-window rows)", "",
          f"Test distribution: {tc['test_distribution']} (n = {tc['test_rows']:,}).", ""]
    rows = []
    for kind in ("hierarchical", "flat"):
        for m, r in tc[kind].items():
            pc = r["per_class"]
            rows.append([kind, MODEL[m], r["accuracy"], r["macro_precision"], r["macro_recall"], r["macro_f1"]]
                        + [pc[c]["f1"] for c in ("benign", "suspicious", "malicious")])
    L += [table(["Strategy", "Model", "Accuracy", "Macro-P", "Macro-R", "Macro-F1", "Benign F1",
                 "Suspicious F1", "Malicious F1"], rows), ""]
    for kind in ("hierarchical", "flat"):
        for m, r in tc[kind].items():
            L += [f"Confusion matrix, {kind} · {MODEL[m]}:", "", cm_table(r["confusion_matrix"], r["labels"]), ""]

    L += ["### A.8 Isolation Forest", "", f"_{iso['note']}_", ""]
    rows = []
    for k, r in iso["experiments"].items():
        if "pr_auc_positive" in r:
            rows.append([k, r.get("fit_on", "–"), r["threshold"], r["pr_auc_positive"], r["positive_rate_baseline"],
                         r["roc_auc"], r["macro_f1"], r["confusion_matrix"]])
    L += [table(["Experiment", "Fitted on", "Threshold", "PR-AUC", "Chance", "ROC-AUC", "Macro-F1",
                 "Confusion matrix"], rows), ""]
    dis = iso["experiments"]["disagreement_with_random_forest"]["rows"]
    cols = list(next(iter(dis.values())).keys())
    L += ["Disagreement with the tuned RF (POOLED test alerts):", "",
          table(["True label"] + cols, [[lab] + [d[c] for c in cols] for lab, d in dis.items()]), ""]

    L += ["### A.9 Saved models (`models/registry.json`)", "",
          table(["Model", "File", "Size MB", "Feature version", "Trained"],
                [[k, v["file"], v["size_mb"], v["feature_version"], v["trained"]] for k, v in reg.items()]), ""]

    tv = MET / "train_val_test.json"
    if tv.exists():
        t = json.loads(tv.read_text(encoding="utf-8"))
        rows = [[m, part, r["accuracy"], r["macro_f1"], r["pr_auc_positive"], r["roc_auc"]]
                for m, d in t["stage2_pooled"].items() for part, r in d.items() if isinstance(r, dict)]
        L += ["### A.10 Train / validation / test (Stage 2 POOLED)", "",
              table(["Model", "Part", "Accuracy", "Macro-F1", "PR-AUC", "ROC-AUC"], rows), ""]
    else:
        L += ["### A.10 Train / validation / test", "",
              "`reports/metrics/train_val_test.json` does not exist yet: `scripts/train_val_test_scores.py` "
              "could not run (Windows Application Control blocked a pandas DLL). See §9.", ""]

    # ---------------------------------------------------------------- raw data
    L += ["## Appendix B. Raw data examples", "",
          "Rows are copied unchanged from `data/samples/` (messages cut at 220 characters). "
          "The WitFoo dataset is already sanitised by its publisher (hosts, users and public IPs are pseudonymised).", ""]
    with (SAMPLES / "witfoo_sample_ORG-0005_test_20min.csv").open(encoding="utf-8", newline="") as f:
        rdr = csv.DictReader(f)
        head = rdr.fieldnames
        picked: dict[str, list] = {"benign": [], "suspicious": [], "malicious": []}
        counts = {k: 0 for k in picked}
        for row in rdr:
            lab = row["reference_label_witfoo"]
            counts[lab] = counts.get(lab, 0) + 1
            if lab in picked and len(picked[lab]) < 3:
                picked[lab].append(row)
    L += ["### B.1 `witfoo_sample_ORG-0005_test_20min.csv`", "",
          f"Columns: {', '.join(f'`{c}`' for c in head)}. Rows per label: {counts}.", ""]
    rows = [[r["timestamp"], r["message_type"], r["action"], r["protocol"], r["src_ip"], r["dst_ip"],
             r["dst_port"], r["message_sanitized"][:220], r["reference_label_witfoo"]]
            for lab in picked for r in picked[lab]]
    L += [table(["timestamp (epoch s)", "message_type", "action", "protocol", "src_ip", "dst_ip", "dst_port",
                 "message", "label"], rows), ""]
    asa = (SAMPLES / "witfoo_sample_asa_lines.log").read_text(encoding="utf-8").splitlines()
    notes = (SAMPLES / "synthetic_non_security_notes.txt").read_text(encoding="utf-8").splitlines()
    L += ["### B.2 `witfoo_sample_asa_lines.log` (first 5 of " + f"{len(asa):,} lines)", "", "```",
          *asa[:5], "```", "", "### B.3 `synthetic_non_security_notes.txt` (all lines; out-of-domain test)", "",
          "```", *notes, "```", ""]
    log = (MET / "train_log.txt").read_text(encoding="utf-8").splitlines()
    L += ["## Appendix C. Training log (`reports/metrics/train_log.txt`, complete)", "", "```", *log, "```", ""]
    return "\n".join(L)


def main() -> None:
    text = REPORT.read_text(encoding="utf-8")
    if MARKER not in text:
        sys.exit(f"marker not found in {REPORT}")
    REPORT.write_text(text.split(MARKER)[0] + appendix(), encoding="utf-8")
    print("appendix written:", REPORT)


if __name__ == "__main__":
    main()
